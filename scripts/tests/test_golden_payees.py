@pytest.mark.parametrize("name, memo, kind, key, hint", DESCRIBED, ids=[f"{n}|{m}" for n, m, *_ in DESCRIBED])
def test_describe_keeps_its_keys(name, memo, kind, key, hint):
    d = describe(name, memo, kind)
    assert (d.key, d.hint) == (key, hint)


@pytest.mark.parametrize("name, key", BRAND_KEYS, ids=[n for n, _ in BRAND_KEYS])
def test_every_chain_keeps_its_key(name, key):
    d = describe(name, "", K)
    assert (d.key, d.hint, d.brand) == (key, "", True)


def test_every_chain_has_a_golden_key():
    """A chain added to BRANDS gets its row in BRAND_KEYS too."""
    assert len(BRAND_KEYS) == len({name for _, name in BRANDS})
